#!/usr/bin/env python3
"""Generate runtime/hle/steam_ifaces.inc (vtable layouts of the Steamworks interfaces Dishonored uses) from Open Steamworks headers.
  mkdir -p private/ref/osw && cd private/ref/osw && for f in <names below>; do
      curl -sfLO "https://raw.githubusercontent.com/SteamRE/open-steamworks/master/Open%20Steamworks/$f.h"; done
  python3 -I runtime/tools/gen_steam_ifaces.py
Per method: name, stack argument bytes (thiscall: `this` in ecx, callee pops the rest; CSteamID/CGameID/64-bit values by value are
8 bytes; a struct return adds the hidden result pointer) and the return kind."""
import os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'private', 'ref', 'osw')
IFACES = [('Utils', 'ISteamUtils005'), ('User', 'ISteamUser016'), ('Friends', 'ISteamFriends011'), ('RemoteStorage', 'ISteamRemoteStorage006'),
          ('UserStats', 'ISteamUserStats010'), ('MatchmakingServers', 'ISteamMatchmakingServers002'), ('Apps', 'ISteamApps005'),
          ('Networking', 'ISteamNetworking005'), ('Matchmaking', 'ISteamMatchmaking009')]
WIDE = {'CSteamID', 'CGameID', 'uint64', 'int64', 'double', 'SteamAPICall_t', 'SteamLeaderboard_t', 'SteamLeaderboardEntries_t', 'UGCHandle_t',
        'PublishedFileId_t', 'UGCFileWriteStreamHandle_t', 'ulonglong', 'ULONGLONG'}
RET64 = WIDE - {'CSteamID', 'CGameID', 'double'}

def arg_bytes(args):
    args = re.sub(r'=\s*[^,]+', '', args).strip()
    if not args or args == 'void': return 0
    n = 0
    for a in args.split(','):
        a = a.strip()
        if '*' in a or '&' in a: n += 4; continue
        t = a.replace('const ', '').split()[0]
        n += 8 if t in WIDE else 4
    return n

def ret_kind(rt):
    rt = rt.replace('const ', '').strip()
    if rt == 'void': return 'Void'
    if rt in ('char *', 'char*'): return 'Str'
    if '*' in rt: return 'Ptr'
    if rt in ('float', 'double'): return 'Float'
    if rt in RET64: return 'U64'
    return 'U32'

out = ['// GENERATED by runtime/tools/gen_steam_ifaces.py from Open Steamworks (SteamRE) headers. Do not edit.',
       '// {name, stack argument bytes, return kind}; slots in vtable order.']
for short, hdr in IFACES:
    path = os.path.join(SRC, hdr + '.h')
    if not os.path.exists(path): sys.exit('missing %s (see the header comment)' % path)
    meths = []
    skip = []   # per nesting level: in the #else branch of an MSVC-vs-GCC block (MSVC builds use the first branch)
    for line in open(path):
        s = line.strip()
        if s.startswith('#if'):
            skip.append(False); continue
        if s.startswith('#else'):
            if skip: skip[-1] = True
            continue
        if s.startswith('#endif'):
            if skip: skip.pop()
            continue
        if any(skip): continue
        m = re.match(r'STEAMWORKS_STRUCT_RETURN_\d+\(\s*(\w+)\s*,\s*(\w+)\s*(,.*)?\)\s*/\*\s*virtual\s+\w+\s+\w+\s*\((.*)\)\s*=\s*0', s)
        if m:
            meths.append((m.group(2), 4 + arg_bytes(m.group(4)), 'Struct8')); continue
        m = re.match(r'virtual\s+(.+?)\s*(\b\w+)\s*\((.*)\)\s*(const\s*)?=\s*0\s*;', s)
        if m:
            meths.append((m.group(2), arg_bytes(m.group(3)), ret_kind(m.group(1))))
    out.append('static const SteamMethod k_%s[] = {' % short)
    for n, b, k in meths: out.append('    {"%s", %d, SteamRet::%s},' % (n, b, k))
    out.append('};')
out.append('static const SteamIface k_steam_ifaces[] = {')
for short, hdr in IFACES: out.append('    {"%s", "%s", k_%s, sizeof k_%s / sizeof k_%s[0]},' % (short, hdr, short, short, short))
out.append('};')
open(os.path.join(ROOT, 'runtime', 'hle', 'steam_ifaces.inc'), 'w').write('\n'.join(out) + '\n')
print('wrote runtime/hle/steam_ifaces.inc:', ', '.join('%s %d' % (s, sum(1 for l in out if False)) for s, _ in []))
