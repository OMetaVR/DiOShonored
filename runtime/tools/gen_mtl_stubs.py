#!/usr/bin/env python3
"""Generate runtime/platform/d3d9_metal/iface_stubs.inc: for each host D3D9 interface, a `Stub_<iface>` class that implements every method
(except IUnknown's) with a loud "not implemented" body, so the Metal backend's classes only override what they really implement.

  python3 -I runtime/tools/gen_mtl_stubs.py [path/to/d3d9.h]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
HDR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "third_party/dxvk/install-linux/include/dxvk/d3d9.h")
OUT = os.path.join(ROOT, "runtime/platform/d3d9_metal/iface_stubs.inc")
IFACES = ["IDirect3D9", "IDirect3DDevice9", "IDirect3DSwapChain9", "IDirect3DSurface9", "IDirect3DVolume9", "IDirect3DTexture9",
          "IDirect3DCubeTexture9", "IDirect3DVolumeTexture9", "IDirect3DVertexBuffer9", "IDirect3DIndexBuffer9", "IDirect3DVertexDeclaration9",
          "IDirect3DVertexShader9", "IDirect3DPixelShader9", "IDirect3DStateBlock9", "IDirect3DQuery9"]
IUNKNOWN = {"QueryInterface", "AddRef", "Release"}

def norm(t):
    t = " ".join(t.replace("struct ", "").split())
    t = t.replace(" *", "*").replace("* ", "*")
    return t

def parse_params(s):
    out = []
    if not s.strip():
        return out
    for p in re.split(r',(?![^()]*\))', s):
        p = " ".join(p.split())
        m = re.match(r'^(.*?)(\w+)(\[\d*\])?$', p)
        if not m or not m.group(1).strip() or m.group(1).strip() in ("const", "struct"):
            typ, name = p, "arg%d" % len(out)
        else:
            typ, name = m.group(1).strip(), m.group(2)
        out.append((norm(typ), "a%d" % len(out)))
    return out

def main():
    text = open(HDR).read()
    res = {}
    for m in re.finditer(r'DECLARE_INTERFACE_\((\w+),\s*(\w+)\)\s*\{(.*?)\n\};', text, re.S):
        name, body = m.group(1), m.group(3)
        if name not in IFACES:
            continue
        methods = []
        for mm in re.finditer(r'STDMETHOD(?:_\(\s*([^,)]+?)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS(_)?\s*(.*?)\)\s*PURE;', body, re.S):
            ret = mm.group(1) or "HRESULT"
            mname = mm.group(2) or mm.group(3)
            methods.append((ret, mname, parse_params(mm.group(5) or "")))
        res[name] = methods
    o = ["// Generated by runtime/tools/gen_mtl_stubs.py from d3d9.h. Do not edit.",
         "// Stub_<iface>: every method answers D3DERR_NOTAVAILABLE (or a zero value) and logs once; backends derive from these and override what they implement."]
    for iface in IFACES:
        o.append("struct Stub_%s : public %s {" % (iface, iface))
        for ret, mname, params in res[iface]:
            if mname in IUNKNOWN:
                continue
            plist = ", ".join("%s %s" % (t, n) for t, n in params)
            retb = ret.replace("const ", "").strip()
            if retb == "void":
                body = '{ stub_called("%s::%s"); }' % (iface, mname)
            elif retb == "HRESULT":
                body = '{ return stub_called("%s::%s"); }' % (iface, mname)
            elif retb == "float":
                body = '{ stub_called("%s::%s"); return 0.0f; }' % (iface, mname)
            else:
                body = '{ stub_called("%s::%s"); return (%s)0; }' % (iface, mname, ret)
            o.append("    STDMETHOD_(%s, %s)(%s) override %s" % (ret, mname, plist, body))
        o.append("};")
    open(OUT, "w").write("\n".join(o) + "\n")
    print("wrote", OUT, sum(len(v) for v in res.values()), "methods")

main()
