#!/usr/bin/env python3
"""Generate docs/runtime_imports.md: which imports are implemented vs auto-stubbed.

  python3 -I runtime/tools/gen_import_report.py <path to dishonored_linux>

Uses `dishonored_linux --dump-hle` for the list of registered implementations and tools/analysis/out/api_surface.json for the imports.
"""
import json, os, re, subprocess, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
exe = sys.argv[1]
out = subprocess.run([exe, "--dump-hle"], capture_output=True, text=True, check=True).stdout
impl = set()
for l in out.splitlines():
    p = l.split("\t")
    if p[0] == "registered":
        impl.add((p[1], p[2]))
sigs = {}
for l in open(os.path.join(ROOT, "runtime", "hle", "sigs_generated.inc")):
    m = re.match(r'\{"([^"]+)", "((?:[^"\\]|\\.)*)", (\d+), \'(.)\', (-?\d+), (-?\d+), (\d+)\}', l)
    if m:
        sigs[(m.group(1), m.group(2).replace("\\\\", "\\"))] = (m.group(4), int(m.group(5)))
surf = json.load(open(os.path.join(ROOT, "tools", "analysis", "out", "api_surface.json")))
rows = collections.defaultdict(lambda: {"impl": [], "stub": [], "unk": [], "crt": []})
# ordinal imports (xinput1_3 ord2/ord3) are mapped through their Wine names
ordmap = {("xinput1_3.dll", "ord2"): "XInputGetState", ("xinput1_3.dll", "ord3"): "XInputSetState"}
for x in surf:
    dll, fn = x["dll"].lower(), x["function"]
    fn = ordmap.get((dll, fn), fn)
    r = rows[dll]
    if x["category"] == "crt":
        r["crt"].append(fn if (dll, fn) not in impl else fn + " (native override)")
    elif (dll, fn) in impl:
        r["impl"].append(fn)
    elif sigs.get((dll, fn), ("?", -1))[0] == "?":
        r["unk"].append(fn)
    else:
        r["stub"].append(fn)
tot = collections.Counter()
for r in rows.values():
    for k, v in r.items():
        tot[k] += len(v)
o = []
o.append("# Runtime imports: implemented vs stubbed\n")
o.append("Generated by `runtime/tools/gen_import_report.py` from `dishonored_linux --dump-hle` and `tools/analysis/out/api_surface.json`. Do not edit by hand.\n")
o.append("- **implemented**: a host function exists (`runtime/hle/*.cpp`, registered with `HLE(...)`).")
o.append("- **stub**: no implementation; the loader binds an auto-generated stub that logs once, pops the right number of bytes (from the Wine .spec signature) and returns the per-function default (0 unless listed in `runtime/tools/manual_sigs.txt`). Calls are counted (`stub_report` at exit).")
o.append("- **stub, signature unknown**: stub that assumes cdecl with no arguments; **not safe for stdcall functions** and must be fixed before the function is ever called.")
o.append("- **crt**: msvcr90/msvcr80/msvcp90 imports. With the CRT recompiled (scenario A) these are lifted guest code, not HLE; a few hot ones have native overrides (`ovr_*`, `runtime/overrides/ovr_crt.cpp`) and are also registered as msvcr90/msvcr80 exports.\n")
o.append("| DLL | implemented | stub | stub, signature unknown | crt |")
o.append("|---|---|---|---|---|")
for dll in sorted(rows):
    r = rows[dll]
    o.append(f"| {dll} | {len(r['impl'])} | {len(r['stub'])} | {len(r['unk'])} | {len(r['crt'])} |")
o.append(f"| **total** | {tot['impl']} | {tot['stub']} | {tot['unk']} | {tot['crt']} |\n")
for dll in sorted(rows):
    r = rows[dll]
    o.append(f"## {dll}\n")
    for key, title in (("impl", "implemented"), ("stub", "stub"), ("unk", "stub, signature unknown"), ("crt", "crt")):
        if r[key]:
            o.append(f"**{title}** ({len(r[key])}): " + ", ".join(f"`{n}`" for n in sorted(r[key])) + "\n")
o.append("## Registered implementations that are not static imports\n")
o.append("Available to `GetProcAddress` / `LoadLibrary`-based lookups (FlsAlloc, SRW locks, InitOnce, ...):\n")
static = {(x["dll"].lower(), ordmap.get((x["dll"].lower(), x["function"]), x["function"])) for x in surf}
extra = sorted(f"{d}!{n}" for d, n in impl if (d, n) not in static and d not in ("test.dll",))
o.append(", ".join(f"`{e}`" for e in extra) + "\n")
open(os.path.join(ROOT, "docs", "runtime_imports.md"), "w").write("\n".join(o))
print("wrote docs/runtime_imports.md:", dict(tot))
