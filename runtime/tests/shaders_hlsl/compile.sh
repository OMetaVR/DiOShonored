#!/bin/sh
# Regenerates ../shaders_corpus_gen.h from the .hlsl files (HLSL -> D3D9 SM3.0 bytecode through Wine's d3dcompiler, like the d3d9_test spike).
# Needs: wine, tools/spikes/hlsl_compile/hlslc.exe, python3. Entry point `main`; `*_vs.hlsl` -> vs_3_0, `*_ps.hlsl` -> ps_3_0.
set -e
here=$(cd "$(dirname "$0")" && pwd)
hlslc="$here/../../../tools/spikes/hlsl_compile/hlslc.exe"
export WINEPREFIX=${WINEPREFIX:-$HOME/.cache/wine-hlslc} WINEDEBUG=-all WINEDLLOVERRIDES="mscoree,mshtml="
out=$(mktemp -d "${TMPDIR:-$HOME/.cache}/hlslc.XXXXXX")
for f in "$here"/*_vs.hlsl "$here"/*_ps.hlsl; do
  n=$(basename "$f" .hlsl)
  case "$n" in *_vs) prof=vs_3_0;; *) prof=ps_3_0;; esac
  wine "$hlslc" "$(winepath -w "$f")" main $prof "$(winepath -w "$out/$n.bin")" "$(winepath -w "$out/$n.txt")" 2>&1 | grep -v 'MESA\|pci id' || true
done
python3 -I - "$out" "$here/../shaders_corpus_gen.h" <<'PY'
import sys, glob, os
d, outp = sys.argv[1], sys.argv[2]
names = sorted(os.path.basename(p)[:-4] for p in glob.glob(d + "/*.bin"))
with open(outp, "w") as f:
    f.write("// GENERATED by shaders_hlsl/compile.sh from shaders_hlsl/*.hlsl (d3dbc SM3.0). Do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n")
    for n in names:
        b = open(f"{d}/{n}.bin", "rb").read()
        words = [int.from_bytes(b[i:i+4], "little") for i in range(0, len(b), 4)]
        f.write(f"static const uint32_t k_corpus_{n}[{len(words)}] = {{\n")
        for i in range(0, len(words), 8):
            f.write("  " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + ",\n")
        f.write("};\n")
    f.write("struct CorpusShader { const char *name; const uint32_t *code; size_t words; };\nstatic const CorpusShader kCorpus[] = {\n")
    for n in names:
        f.write(f'  {{"{n}", k_corpus_{n}, sizeof(k_corpus_{n}) / 4}},\n')
    f.write("};\n")
PY
echo "wrote $here/../shaders_corpus_gen.h"
