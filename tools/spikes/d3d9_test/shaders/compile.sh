#!/bin/sh
# Regenerates ../shaders_gen.h from the .hlsl files (HLSL -> D3D9 SM3.0 bytecode).
# Needs: wine, tools/spikes/hlsl_compile/hlslc.exe (mingw build), python3.
set -e
here=$(cd "$(dirname "$0")" && pwd)
hlslc="$here/../../hlsl_compile/hlslc.exe"
export WINEPREFIX=${WINEPREFIX:-$HOME/.cache/wine-hlslc} WINEDEBUG=-all WINEDLLOVERRIDES="mscoree,mshtml="
out=$(mktemp -d "${TMPDIR:-$HOME/.cache}/hlslc.XXXXXX")
wine "$hlslc" "$(winepath -w $here/scene_vs.hlsl)" main vs_3_0 "$(winepath -w $out/scene_vs.bin)" "$(winepath -w $out/scene_vs.txt)"
wine "$hlslc" "$(winepath -w $here/scene_ps.hlsl)" main ps_3_0 "$(winepath -w $out/scene_ps.bin)" "$(winepath -w $out/scene_ps.txt)"
wine "$hlslc" "$(winepath -w $here/rtt_ps.hlsl)"   main ps_3_0 "$(winepath -w $out/rtt_ps.bin)"   "$(winepath -w $out/rtt_ps.txt)"
python3 -I - "$out" "$here/../shaders_gen.h" <<'PY'
import sys
d, outp = sys.argv[1], sys.argv[2]
with open(outp, "w") as f:
    f.write("// GENERATED by shaders/compile.sh from shaders/*.hlsl (d3dbc SM3.0). Do not edit.\n#pragma once\n#include <stdint.h>\n")
    for n in ("scene_vs", "scene_ps", "rtt_ps"):
        b = open(f"{d}/{n}.bin", "rb").read()
        assert len(b) % 4 == 0
        words = [int.from_bytes(b[i:i+4], "little") for i in range(0, len(b), 4)]
        f.write(f"static const uint32_t k_{n}[{len(words)}] = {{\n")
        for i in range(0, len(words), 8):
            f.write("  " + ", ".join(f"0x{w:08x}" for w in words[i:i+8]) + ",\n")
        f.write("};\n")
PY
cp $out/*.txt "$here/" 2>/dev/null || true
echo "wrote $here/../shaders_gen.h"
