//! Text of the generated header `gen.h` (shared by all shards).

pub fn gen_h(simd: &str) -> String {
    let mut s = String::new();
    s.push_str(
        r#"/* gen.h: generated by the lifter. Shared definitions for lifted code. Do not edit. */
#ifndef LX_GEN_H
#define LX_GEN_H

#include <stdint.h>
#ifdef LX_BASE_REG
/* experimental: dedicated base register (arm64: x27). The runtime must set it on every entry into lifted code. */
#  define GUEST_MB lx_gb
#  if defined(__aarch64__)
register uint8_t *lx_gb __asm__("x27");
#  else
#    error "LX_BASE_REG is only implemented for aarch64"
#  endif
#else
#  define GUEST_MB mb
#endif
#include "guest_abi.h"

/* Extended-signature return: GuestRet plus the registers a function breaks the callee-saved convention with.
 * x[0]=ebx x[1]=esi x[2]=edi x[3]=ebp x[4]=ecx */
typedef struct LxExt { GuestRet r; uint32_t x[5]; } LxExt;


/* EH landing pads: _setjmp itself must be called in the lifted function's frame (libc symbol, declared here because generated
 * code includes no libc headers) */
int _setjmp(void *jb) __attribute__((returns_twice));
#define lx_setjmp(jb) _setjmp(jb)

/* debug tracing (lifter --trace) */
void lx_trace_enter(uint32_t a, uint32_t esp, uint32_t eax, uint32_t ecx, uint32_t edx);

/* ---- calls ------------------------------------------------------------------------------------- */
#define LX_CALLD(fn, popc) do { GuestRet r_ = fn(esp - 4u, eax, ecx, edx); eax = (uint32_t)r_.r0; edx = (uint32_t)r_.r1; esp += (popc); } while (0)
#define LX_CALLD_DYN(fn)   do { GuestRet r_ = fn(esp - 4u, eax, ecx, edx); eax = (uint32_t)r_.r0; edx = (uint32_t)r_.r1; esp += (uint32_t)(r_.r0 >> 32); } while (0)
#define LX_CALLI(t)        do { GuestRet r_ = guest_call((t), esp - 4u, eax, ecx, edx); eax = (uint32_t)r_.r0; edx = (uint32_t)r_.r1; esp += (uint32_t)(r_.r0 >> 32); } while (0)

/* ---- shared accesses with possibly unaligned addresses ----------------------------------------------------
 * aarch64 acquire/release accesses must be naturally aligned, so a shared access of unknown alignment tests the address.
 * Policies (selected at C compile time, no re-lift needed):
 *   default                 aligned: LDAPR/STLR inline; misaligned: out-of-line plain-access slow path
 *   -DLX_ASSUME_ALIGNED     LDAPR/STLR only (a misaligned shared access faults on arm64)
 *   -DGUEST_RELAXED_ORDERING  plain loads/stores (header contract)                                             */
#if defined(__aarch64__) && !defined(GUEST_RELAXED_ORDERING) && !defined(LX_ASSUME_ALIGNED)
#  define LX_DEF_SU(T, N, M) \
    static inline __attribute__((always_inline)) T lx_ldslow_##N(uint8_t *base, uint32_t a) { T v; __builtin_memcpy(&v, base + a, sizeof(T)); return v; } \
    static inline __attribute__((always_inline)) void lx_stslow_##N(uint8_t *base, uint32_t a, T v) { __builtin_memcpy(base + a, &v, sizeof(T)); } \
    static inline __attribute__((always_inline)) T lx_ldsu_##N(uint8_t *base, uint32_t a) { return __builtin_expect((a & M) == 0, 1) ? __atomic_load_n((T *)(base + a), __ATOMIC_ACQUIRE) : lx_ldslow_##N(base, a); } \
    static inline __attribute__((always_inline)) void lx_stsu_##N(uint8_t *base, uint32_t a, T v) { if (__builtin_expect((a & M) == 0, 1)) __atomic_store_n((T *)(base + a), v, __ATOMIC_RELEASE); else lx_stslow_##N(base, a, v); }
LX_DEF_SU(uint16_t, 2, 1u)
LX_DEF_SU(uint32_t, 4, 3u)
LX_DEF_SU(uint64_t, 8, 7u)
#  define LX_LD_SU2(a) lx_ldsu_2(GUEST_MB, (uint32_t)(a))
#  define LX_LD_SU4(a) lx_ldsu_4(GUEST_MB, (uint32_t)(a))
#  define LX_LD_SU8(a) lx_ldsu_8(GUEST_MB, (uint32_t)(a))
#  define LX_ST_SU2(a, v) lx_stsu_2(GUEST_MB, (uint32_t)(a), (uint16_t)(v))
#  define LX_ST_SU4(a, v) lx_stsu_4(GUEST_MB, (uint32_t)(a), (uint32_t)(v))
#  define LX_ST_SU8(a, v) lx_stsu_8(GUEST_MB, (uint32_t)(a), (uint64_t)(v))
#elif defined(__aarch64__) && defined(LX_ASSUME_ALIGNED) && !defined(GUEST_RELAXED_ORDERING)
#  define LX_LD_SU2(a) GUEST_LD_SHARED(uint16_t, (uint32_t)(a))
#  define LX_LD_SU4(a) GUEST_LD_SHARED(uint32_t, (uint32_t)(a))
#  define LX_LD_SU8(a) GUEST_LD_SHARED(uint64_t, (uint32_t)(a))
#  define LX_ST_SU2(a, v) GUEST_ST_SHARED(uint16_t, (uint32_t)(a), (v))
#  define LX_ST_SU4(a, v) GUEST_ST_SHARED(uint32_t, (uint32_t)(a), (v))
#  define LX_ST_SU8(a, v) GUEST_ST_SHARED(uint64_t, (uint32_t)(a), (v))
#elif (defined(__x86_64__) || defined(__i386__)) && !defined(GUEST_RELAXED_ORDERING)
/* x86 hosts order loads and stores like the guest (TSO); the compiler must not reorder, merge or drop them either, or the guest's
 * lock-free code breaks (PhysX's task queues corrupted at gameplay start). volatile through an alignment-1 type: unaligned is fine. */
typedef uint16_t __attribute__((aligned(1), may_alias)) lx_u16u;
typedef uint32_t __attribute__((aligned(1), may_alias)) lx_u32u;
typedef uint64_t __attribute__((aligned(1), may_alias)) lx_u64u;
#  define LX_LD_SU2(a) (*(volatile lx_u16u *)(GUEST_MB + (uint32_t)(a)))
#  define LX_LD_SU4(a) (*(volatile lx_u32u *)(GUEST_MB + (uint32_t)(a)))
#  define LX_LD_SU8(a) (*(volatile lx_u64u *)(GUEST_MB + (uint32_t)(a)))
#  define LX_ST_SU2(a, v) (*(volatile lx_u16u *)(GUEST_MB + (uint32_t)(a)) = (uint16_t)(v))
#  define LX_ST_SU4(a, v) (*(volatile lx_u32u *)(GUEST_MB + (uint32_t)(a)) = (uint32_t)(v))
#  define LX_ST_SU8(a, v) (*(volatile lx_u64u *)(GUEST_MB + (uint32_t)(a)) = (uint64_t)(v))
#else
static inline __attribute__((always_inline)) uint16_t lx_ldu16(uint8_t *b, uint32_t a) { uint16_t v; __builtin_memcpy(&v, b + a, 2); return v; }
static inline __attribute__((always_inline)) uint32_t lx_ldu32(uint8_t *b, uint32_t a) { uint32_t v; __builtin_memcpy(&v, b + a, 4); return v; }
static inline __attribute__((always_inline)) uint64_t lx_ldu64(uint8_t *b, uint32_t a) { uint64_t v; __builtin_memcpy(&v, b + a, 8); return v; }
#  define LX_LD_SU2(a) lx_ldu16(GUEST_MB, (uint32_t)(a))
#  define LX_LD_SU4(a) lx_ldu32(GUEST_MB, (uint32_t)(a))
#  define LX_LD_SU8(a) lx_ldu64(GUEST_MB, (uint32_t)(a))
#  define LX_ST_SU2(a, v) do { uint16_t v_ = (uint16_t)(v); __builtin_memcpy(GUEST_MB + (uint32_t)(a), &v_, 2); } while (0)
#  define LX_ST_SU4(a, v) do { uint32_t v_ = (uint32_t)(v); __builtin_memcpy(GUEST_MB + (uint32_t)(a), &v_, 4); } while (0)
#  define LX_ST_SU8(a, v) do { uint64_t v_ = (uint64_t)(v); __builtin_memcpy(GUEST_MB + (uint32_t)(a), &v_, 8); } while (0)
#endif

/* ---- floating point helpers --------------------------------------------------------------------- */
static inline float lx_f32_from_bits(uint32_t u) { float f; __builtin_memcpy(&f, &u, 4); return f; }
static inline uint32_t lx_f32_to_bits(float f) { uint32_t u; __builtin_memcpy(&u, &f, 4); return u; }
static inline double lx_f64_from_bits(uint64_t u) { double f; __builtin_memcpy(&f, &u, 8); return f; }
static inline uint64_t lx_f64_to_bits(double f) { uint64_t u; __builtin_memcpy(&u, &f, 8); return u; }

/* x87 80-bit extended <-> double (round to nearest even on narrowing) */
static inline double lx_ld80(const uint8_t *p) {
    uint64_t m; uint16_t se;
    __builtin_memcpy(&m, p, 8); __builtin_memcpy(&se, p + 8, 2);
    uint32_t sign = se >> 15; int32_t e = se & 0x7fff;
    uint64_t sbit = (uint64_t)sign << 63;
    if (e == 0x7fff) {
        if ((m << 1) == 0) return lx_f64_from_bits(sbit | 0x7ff0000000000000ull);
        return lx_f64_from_bits(sbit | 0x7ff8000000000000ull | ((m << 1) >> 12));
    }
    if (m == 0) return lx_f64_from_bits(sbit);
    int32_t ex = (e == 0 ? 1 : e) - 16383;          /* unbiased exponent of the integer-bit-normalised value */
    int lz = __builtin_clzll(m);                    /* normalise (handles denormals / pseudo-denormals) */
    m <<= lz; ex -= lz;
    int32_t de = ex + 1023;
    if (de >= 0x7ff) return lx_f64_from_bits(sbit | 0x7ff0000000000000ull);
    if (de <= 0) {                                   /* result is a double denormal or zero */
        int sh = 11 + (1 - de);
        if (sh >= 64) return lx_f64_from_bits(sbit);
        uint64_t q = m >> sh, rem = m << (64 - sh), half = 1ull << 63;
        if (rem > half || (rem == half && (q & 1))) q++;
        return lx_f64_from_bits(sbit | q);
    }
    uint64_t q = m >> 11, rem = m << 53, half = 1ull << 63;     /* 53 significant bits incl. integer bit */
    if (rem > half || (rem == half && (q & 1))) q++;
    uint64_t bits = ((uint64_t)de << 52) + (q - (1ull << 52));
    return lx_f64_from_bits(sbit | bits);
}
static inline void lx_st80(uint8_t *p, double d) {
    uint64_t u = lx_f64_to_bits(d); uint64_t m; uint16_t se;
    uint32_t sign = (uint32_t)(u >> 63); int32_t e = (int32_t)((u >> 52) & 0x7ff); uint64_t f = u & 0xfffffffffffffull;
    if (e == 0x7ff) { se = (uint16_t)((sign << 15) | 0x7fff); m = 0x8000000000000000ull | (f << 11); if (f) m |= 0x4000000000000000ull; }
    else if (e == 0) {
        if (f == 0) { se = (uint16_t)(sign << 15); m = 0; }
        else { int lz = __builtin_clzll(f); m = f << lz; se = (uint16_t)((sign << 15) | (uint32_t)(16383 - 1022 - (lz - 11))); }
    } else { se = (uint16_t)((sign << 15) | (uint32_t)(e - 1023 + 16383)); m = 0x8000000000000000ull | (f << 11); }
    __builtin_memcpy(p, &m, 8); __builtin_memcpy(p + 8, &se, 2);
}
static inline double lx_round_cw(double x, uint32_t cw) {
    switch ((cw >> 10) & 3) { case 0: return __builtin_rint(x); case 1: return __builtin_floor(x); case 2: return __builtin_ceil(x); default: return __builtin_trunc(x); }
}
static inline double lx_rndint(double x, uint32_t cw) { return lx_round_cw(x, cw); }
static inline uint16_t lx_fist16(double x, uint32_t cw, int u) { (void)u; double r = lx_round_cw(x, cw); if (!(r >= -32768.0 && r < 32768.0)) return 0x8000u; return (uint16_t)(int16_t)r; }
static inline uint32_t lx_fist32(double x, uint32_t cw) { double r = lx_round_cw(x, cw); if (!(r >= -2147483648.0 && r < 2147483648.0)) return 0x80000000u; return (uint32_t)(int32_t)r; }
static inline uint64_t lx_fist64(double x, uint32_t cw) { double r = lx_round_cw(x, cw); if (!(r >= -9223372036854775808.0 && r < 9223372036854775808.0)) return 0x8000000000000000ull; return (uint64_t)(int64_t)r; }
static inline uint16_t lx_fxam(double x) {
    uint64_t u = lx_f64_to_bits(x); uint16_t c1 = (u >> 63) ? 0x200 : 0;
    uint32_t e = (uint32_t)((u >> 52) & 0x7ff); uint64_t f = u & 0xfffffffffffffull;
    if (e == 0x7ff) return (uint16_t)((f ? 0x100 : 0x500) | c1);
    if (e == 0) return (uint16_t)((f ? 0x4400 : 0x4000) | c1);
    return (uint16_t)(0x400 | c1);
}
static inline double lx_fscale(double a, double b) {
    if (b != b) return b;
    if (b > 4096.0) b = 4096.0; else if (b < -4096.0) b = -4096.0;
    return __builtin_scalbn(a, (int)__builtin_trunc(b));
}
static inline double lx_fprem(double a, double b, int ieee, uint16_t *fcc) {
    double r, q;
    if (ieee) { r = __builtin_remainder(a, b); q = __builtin_rint((a - r) / b); }
    else { r = __builtin_fmod(a, b); q = __builtin_trunc((a - r) / b); }
    uint32_t qi = (uint32_t)(uint64_t)__builtin_fabs(__builtin_fmod(q, 8.0));
    *fcc = (uint16_t)(((qi & 1) ? 0x200 : 0) | ((qi & 2) ? 0x4000 : 0) | ((qi & 4) ? 0x100 : 0));
    return r;
}

/* ---- misc instructions ------------------------------------------------------------------------- */
static inline void lx_cpuid(uint32_t *eax, uint32_t *ebx, uint32_t *ecx, uint32_t *edx) {
    uint32_t leaf = *eax;
    switch (leaf) {
    case 0:  *eax = 1; *ebx = 0x756e6547u; *edx = 0x49656e69u; *ecx = 0x6c65746eu; break;      /* "GenuineIntel" */
    case 1:  *eax = 0x000106A5u; *ebx = 0x00010800u; *ecx = 0x00000000u; *edx = 0x0789FBFFu & ~(1u << 28); break; /* SSE2, no SSE3+ */
    case 0x80000000u: *eax = 0x80000000u; *ebx = *ecx = *edx = 0; break;
    default: *eax = *ebx = *ecx = *edx = 0; break;
    }
}
static inline void lx_rdtsc(uint32_t *eax, uint32_t *edx) { uint64_t t = __builtin_readcyclecounter(); *eax = (uint32_t)t; *edx = (uint32_t)(t >> 32); }

typedef long long v128 __attribute__((vector_size(16)));
"#,
    );
    s.push_str(include_str!("simd.h.in"));
    s.push_str(simd);
    s.push_str("\n#endif /* LX_GEN_H */\n");
    s
}
