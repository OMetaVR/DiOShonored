pub struct Shard {
    pub module: usize,
    pub index: usize,
    pub funcs: Vec<usize>, // indices into outs
    pub n_x86: u64,
}

pub fn make_shards(outs: &[FnOut], nmod: usize, limit: usize) -> Vec<Shard> {
    let mut shards: Vec<Shard> = Vec::new();
    for m in 0..nmod {
        let mut idx: Vec<usize> = (0..outs.len()).filter(|&i| outs[i].module == m).collect();
        idx.sort_by_key(|&i| outs[i].addr);
        let mut cur = Shard { module: m, index: 0, funcs: vec![], n_x86: 0 };
        let mut k = 0;
        for i in idx {
            if cur.n_x86 as usize >= limit && !cur.funcs.is_empty() {
                shards.push(cur);
                k += 1;
                cur = Shard { module: m, index: k, funcs: vec![], n_x86: 0 };
            }
            cur.n_x86 += outs[i].n_x86 as u64;
            cur.funcs.push(i);
        }
        if !cur.funcs.is_empty() {
            shards.push(cur);
        }
    }
    shards
}

fn proto(addr: u32, ext: bool, sigs: &std::collections::HashMap<u32, Sig>) -> String {
    let s = sigs.get(&addr).cloned().unwrap_or_default();
    if ext {
        let mut p = String::from("uint32_t, uint32_t, uint32_t, uint32_t");
        for g in EXT_ORDER {
            if s.ext_in & ext_bit(g) != 0 {
                p.push_str(", uint32_t");
            }
        }
        format!("LxExt {}_x({});", gname(addr), p)
    } else {
        format!("GuestRet {}(uint32_t, uint32_t, uint32_t, uint32_t);", gname(addr))
    }
}

pub fn write_shard(ctx: &LiftCtx, an: &Analysis, outs: &[FnOut], sh: &Shard, path: &Path) -> Result<()> {
    let mut s = String::new();
    s.push_str("/* generated by the lifter; do not edit */\n#include \"gen.h\"\n\n");
    let mut defined: BTreeSet<u32> = BTreeSet::new();
    for &i in &sh.funcs {
        defined.insert(outs[i].addr);
    }
    let mut refs: BTreeSet<(u32, bool)> = BTreeSet::new();
    let mut ovr: BTreeSet<String> = BTreeSet::new();
    let mut x87: BTreeSet<String> = BTreeSet::new();
    for &i in &sh.funcs {
        for r in &outs[i].refs {
            if !defined.contains(&r.0) {
                refs.insert(*r);
            }
        }
        ovr.extend(outs[i].ovr_refs.iter().cloned());
        x87.extend(outs[i].x87_refs.iter().cloned());
    }
    // functions in the same shard may need ext prototypes too (forward references)
    let mut local_fwd: BTreeSet<(u32, bool)> = BTreeSet::new();
    for &i in &sh.funcs {
        for r in &outs[i].refs {
            if defined.contains(&r.0) {
                local_fwd.insert(*r);
            }
        }
    }
    for (a, e) in refs.iter().chain(local_fwd.iter()) {
        let _ = writeln!(s, "{}", proto(*a, *e, &an.sigs));
    }
    for o in &ovr {
        let _ = writeln!(s, "GuestRet {o}(uint32_t, uint32_t, uint32_t, uint32_t);");
    }
    let kinds: BTreeMap<&str, OvrKind> = ctx.overrides.values().map(|o| (o.host.as_str(), o.kind)).collect();
    for x in x87.iter().filter(|x| !x.starts_with("__builtin_")) {
        match kinds.get(x.as_str()) {
            Some(OvrKind::X87_2) => {
                let _ = writeln!(s, "double {x}(double, double);");
            }
            _ => {
                let _ = writeln!(s, "double {x}(double);");
            }
        }
    }
    s.push('\n');
    for &i in &sh.funcs {
        s.push_str(&outs[i].text);
        s.push('\n');
    }
    fs::write(path, s)?;
    Ok(())
}

// ---------------------------------------------------------------------------------------------- perfect hash
pub struct Phf {
    pub nslots: u32,
    pub nbuckets: u32,
    pub disp: Vec<u16>,
    pub slot_key: Vec<u32>, // key per slot (0 = empty)
    pub slot_idx: Vec<u32>, // index into the provided key list per slot
}

fn bucket_of(a: u32, nb: u32) -> u32 {
    (((a.wrapping_mul(0x9E3779B1) as u64) * nb as u64) >> 32) as u32
}
fn slot_of(a: u32, seed: u32, ns: u32) -> u32 {
    let mut h = (a ^ seed.wrapping_mul(0x85EBCA6B)).wrapping_mul(0xC2B2AE35);
    h ^= h >> 15;
    h = h.wrapping_mul(0x2C1B3C6D);
    (((h as u64) * ns as u64) >> 32) as u32
}

pub fn build_phf(keys: &[u32]) -> Phf {
    let n = keys.len() as u32;
    let mut load = 1.25f64;
    let mut per_bucket = 4.0f64;
    loop {
        let ns = ((n as f64 * load).ceil() as u32).max(8) | 1;
        let nb = ((n as f64 / per_bucket).ceil() as u32).max(1);
        let mut buckets: Vec<Vec<u32>> = vec![Vec::new(); nb as usize];
        for (i, &k) in keys.iter().enumerate() {
            buckets[bucket_of(k, nb) as usize].push(i as u32);
        }
        let mut order: Vec<usize> = (0..nb as usize).collect();
        order.sort_by(|&a, &b| buckets[b].len().cmp(&buckets[a].len()).then(a.cmp(&b)));
        let mut used = vec![false; ns as usize];
        let mut disp = vec![0u16; nb as usize];
        let mut slot_key = vec![0u32; ns as usize];
        let mut slot_idx = vec![u32::MAX; ns as usize];
        let mut ok = true;
        'outer: for &b in &order {
            if buckets[b].is_empty() {
                continue;
            }
            for seed in 0..=65535u32 {
                let slots: Vec<u32> = buckets[b].iter().map(|&i| slot_of(keys[i as usize], seed, ns)).collect();
                let mut good = true;
                for (j, &s) in slots.iter().enumerate() {
                    if used[s as usize] || slots[..j].contains(&s) {
                        good = false;
                        break;
                    }
                }
                if good {
                    for (j, &s) in slots.iter().enumerate() {
                        used[s as usize] = true;
                        slot_key[s as usize] = keys[buckets[b][j] as usize];
                        slot_idx[s as usize] = buckets[b][j];
                    }
                    disp[b] = seed as u16;
                    continue 'outer;
                }
            }
            ok = false;
            break;
        }
        if ok {
            return Phf { nslots: ns, nbuckets: nb, disp, slot_key, slot_idx };
        }
        load += 0.1;
        per_bucket = (per_bucket - 0.5).max(1.5);
    }
}

pub fn write_dispatch(ctx: &LiftCtx, an: &Analysis, outdir: &Path) -> Result<usize> {
    let all = ctx.all_funcs();
    let mut keys: Vec<u32> = Vec::new();
    let mut targets: Vec<String> = Vec::new();
    let mut decl = String::new();
    let mut ovr_decl: BTreeSet<String> = BTreeSet::new();
    for (&a, _) in &all {
        keys.push(a);
        if let Some(o) = ctx.overrides.get(&a) {
            if o.kind == OvrKind::GuestFn {
                ovr_decl.insert(o.host.clone());
                targets.push(o.host.clone());
                continue;
            }
        }
        let _ = writeln!(decl, "extern GuestRet {}(uint32_t, uint32_t, uint32_t, uint32_t);", gname(a));
        targets.push(gname(a));
    }
    let phf = build_phf(&keys);
    let mut s = String::new();
    s.push_str("/* generated by the lifter; do not edit */\n#include \"gen.h\"\n\n");
    s.push_str(&decl);
    for o in &ovr_decl {
        let _ = writeln!(s, "extern GuestRet {o}(uint32_t, uint32_t, uint32_t, uint32_t);");
    }

    let _ = writeln!(s, "#define LX_NB {}u\n#define LX_NS {}u\n", phf.nbuckets, phf.nslots);
    let _ = write!(s, "static const uint16_t lx_disp[LX_NB] = {{");
    for (i, d) in phf.disp.iter().enumerate() {
        if i % 24 == 0 {
            s.push_str("\n ");
        }
        let _ = write!(s, "{d},");
    }
    s.push_str("\n};\n\n");
    s.push_str("struct LxEnt { uint32_t key; GuestFn fn; };\nstatic const struct LxEnt lx_tab[LX_NS] = {\n");
    for slot in 0..phf.nslots as usize {
        if phf.slot_idx[slot] == u32::MAX {
            continue;
        }
        let i = phf.slot_idx[slot] as usize;
        let _ = writeln!(s, "  [{}] = {{ {:#x}u, {} }},", slot, keys[i], targets[i]);
    }
    s.push_str("};\n\n");
    s.push_str(
        r#"GuestFn guest_lookup(uint32_t a) {
    uint32_t b = (uint32_t)(((uint64_t)(a * 0x9E3779B1u) * LX_NB) >> 32);
    uint32_t seed = lx_disp[b];
    uint32_t h = (a ^ (seed * 0x85EBCA6Bu)) * 0xC2B2AE35u;
    h ^= h >> 15;
    h *= 0x2C1B3C6Du;
    uint32_t slot = (uint32_t)(((uint64_t)h * LX_NS) >> 32);
    return lx_tab[slot].key == a ? lx_tab[slot].fn : (GuestFn)0;
}
"#,
    );
    fs::write(outdir.join("dispatch.c"), s)?;
    let _ = an;
    Ok(keys.len())
}

fn cstr(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

pub fn write_program(ctx: &LiftCtx, outdir: &Path) -> Result<()> {
    let p = &ctx.prog;
    let mut s = String::new();
    s.push_str("/* generated by the lifter; do not edit */\n#include \"gen.h\"\n\n");
    s.push_str("static const GuestModuleDesc lx_modules[] = {\n");
    for m in &p.images {
        let sha: Vec<String> = m.sha256.iter().map(|b| format!("{b:#04x}")).collect();
        let _ = writeln!(
            s,
            "  {{ {}, {}, {{{}}}, {:#x}u, {:#x}u, {:#x}u, {:#x}u, {} }},",
            cstr(&m.name),
            cstr(&m.relpath),
            sha.join(","),
            m.base,
            m.preferred_base,
            m.size_of_image,
            m.entry,
            if m.is_dll { 1 } else { 0 }
        );
    }
    s.push_str("};\n\nstatic const GuestImportDesc lx_imports[] = {\n");
    for i in &p.imports {
        let _ = writeln!(s, "  {{ {}, {}, {} }},", cstr(&i.dll), i.name.as_ref().map(|n| cstr(n)).unwrap_or("0".into()), i.ordinal);
    }
    if p.imports.is_empty() {
        s.push_str("  { 0, 0, 0 },\n");
    }
    s.push_str("};\n\nstatic const GuestIatEntry lx_iat[] = {\n");
    for (slot, t) in &p.iat {
        match t {
            IatTarget::Guest(a) => {
                let _ = writeln!(s, "  {{ {:#x}u, GUEST_IAT_GUEST_ADDR, {:#x}u }},", slot, a);
            }
            IatTarget::Import(i) => {
                let _ = writeln!(s, "  {{ {:#x}u, GUEST_IAT_IMPORT, {}u }},", slot, i);
            }
        }
    }
    s.push_str("};\n\n");
    let _ = writeln!(
        s,
        "const GuestProgram guest_program = {{ GUEST_ABI_VERSION, lx_modules, {}u, lx_imports, {}u, lx_iat, {}u }};",
        p.images.len(),
        p.imports.len(),
        p.iat.len()
    );
    fs::write(outdir.join("program.c"), s)?;
    Ok(())
}

pub fn gpr_name(g: Gpr) -> &'static str {
    g.name()
}
